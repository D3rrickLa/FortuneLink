package com.laderrco.fortunelink.portfolio.domain.model.valueobjects.financial;

import static org.assertj.core.api.Assertions.assertThat;

import com.laderrco.fortunelink.portfolio.domain.model.valueobjects.identifiers.AssetSymbol;
import java.math.BigDecimal;
import java.time.Instant;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class MarketAssetQuoteTest {

  @Test
  @DisplayName("MarketAssetQuote should correctly retain all constructor properties")
  void shouldRetainProperties() {
    // Arrange
    AssetSymbol symbol = new AssetSymbol("AAPL");
    Price currentPrice = Price.of(BigDecimal.valueOf(180.50), Currency.USD);
    Price openPrice = Price.of(BigDecimal.valueOf(179.00), Currency.USD);
    Price highPrice = Price.of(BigDecimal.valueOf(181.00), Currency.USD);
    Price lowPrice = Price.of(BigDecimal.valueOf(178.50), Currency.USD);
    Price previousClose = Price.of(BigDecimal.valueOf(178.00), Currency.USD);
    PercentageChange changePercent = new PercentageChange(BigDecimal.valueOf(1.4));
    BigDecimal changeAmount = BigDecimal.valueOf(2.50);
    BigDecimal marketCap = new BigDecimal("3000000000000");
    BigDecimal volume = BigDecimal.valueOf(55000000);
    String source = "YahooFinance";
    Instant timestamp = Instant.now();

    // Act
    MarketAssetQuote quote = new MarketAssetQuote(
        symbol, currentPrice, openPrice, highPrice, lowPrice, previousClose,
        changePercent, changeAmount, marketCap, volume, source, timestamp
    );

    // Assert individual record component getters
    assertThat(quote.symbol()).isEqualTo(symbol);
    assertThat(quote.currentPrice()).isEqualTo(currentPrice);
    assertThat(quote.openPrice()).isEqualTo(openPrice);
    assertThat(quote.highPrice()).isEqualTo(highPrice);
    assertThat(quote.lowPrice()).isEqualTo(lowPrice);
    assertThat(quote.previousClose()).isEqualTo(previousClose);
    assertThat(quote.changePercent()).isEqualTo(changePercent);
    assertThat(quote.changeAmount()).isEqualByComparingTo(changeAmount);
    assertThat(quote.marketCap()).isEqualByComparingTo(marketCap);
    assertThat(quote.volume()).isEqualByComparingTo(volume);
    assertThat(quote.source()).isEqualTo(source);
    assertThat(quote.timestamp()).isEqualTo(timestamp);
  }

  @Test
  @DisplayName("MarketAssetQuote should correctly evaluate equality and string representation")
  void testValueObjectBehavior() {
    Instant now = Instant.now();
    AssetSymbol symbol = new AssetSymbol("MSFT");
    Price price = Price.of(BigDecimal.valueOf(420.00), Currency.USD);
    PercentageChange pct = new PercentageChange(BigDecimal.valueOf(0.0));

    MarketAssetQuote quote1 = new MarketAssetQuote(
        symbol, price, price, price, price, price,
        pct, BigDecimal.ZERO, BigDecimal.ZERO, BigDecimal.ZERO, "AlphaVantage", now
    );

    MarketAssetQuote quote2 = new MarketAssetQuote(
        symbol, price, price, price, price, price,
        pct, BigDecimal.ZERO, BigDecimal.ZERO, BigDecimal.ZERO, "AlphaVantage", now
    );

    // Verifies equals() and hashCode() contracts generated by Java Records
    assertThat(quote1).isEqualTo(quote2);
    assertThat(quote1.hashCode()).isEqualTo(quote2.hashCode());

    // Verifies toString() contains key structural information
    assertThat(quote1.toString())
        .contains("MarketAssetQuote")
        .contains("symbol=MSFT")
        .contains("source=AlphaVantage");
  }
}